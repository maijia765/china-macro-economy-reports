def td(t):
    return f"<td>{t}</td>"


def table(headers, rows, minw=None):
    style = f' style="min-width:{minw}px"' if minw else ""
    out = [f'<div class="tbl"><table{style}>']
    out.append("<tr>" + "".join(f"<th>{h}</th>" for h in headers) + "</tr>")
    for r in rows:
        out.append("<tr>" + "".join(td(c) for c in r) + "</tr>")
    out.append("</table></div>")
    return "".join(out)


