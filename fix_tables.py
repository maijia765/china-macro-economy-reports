def replace(path, old, new):
    with open(path, encoding="utf-8") as f:
        txt = f.read()
    if old not in txt:
        return False
    txt = txt.replace(old, new, 1)
    with open(path, "w", encoding="utf-8") as f:
        f.write(txt)
    return True


def replace_re(path, pattern, new):
    with open(path, encoding="utf-8") as f:
        txt = f.read()
    txt2, n = re.subn(pattern, new, txt, count=1, flags=re.S)
    if n == 0:
        return False
    with open(path, "w", encoding="utf-8") as f:
        f.write(txt2)
    return True


